from abc import ABC, abstractmethod
from typing import Optional, List, Tuple
from datetime import datetime
from uuid import UUID
from app.domain.entities.sync_entities import EntityVersion, SyncBatch, ConflictLog, SyncLog


class EntityVersionRepository(ABC):
    @abstractmethod
    async def get(self, org_id: UUID, entity_type: str, entity_id: UUID) -> Optional[EntityVersion]: ...
    @abstractmethod
    async def upsert(self, ver: EntityVersion) -> EntityVersion: ...
    @abstractmethod
    async def list_since(self, org_id: UUID, since: datetime, types: Optional[List[str]] = None) -> List[EntityVersion]: ...
    @abstractmethod
    async def list_all(self, org_id: UUID, types: Optional[List[str]] = None) -> List[EntityVersion]: ...
    @abstractmethod
    async def get_next_version(self, org_id: UUID, entity_type: str, entity_id: UUID) -> int: ...


class SyncBatchRepository(ABC):
    @abstractmethod
    async def create(self, b: SyncBatch) -> SyncBatch: ...
    @abstractmethod
    async def update(self, b: SyncBatch) -> SyncBatch: ...
    @abstractmethod
    async def get_last(self, org_id: UUID, direction: str) -> Optional[SyncBatch]: ...
    @abstractmethod
    async def get_by_org_batch(self, org_id: UUID, batch_id: str, direction: str) -> Optional[SyncBatch]: ...


class ConflictLogRepository(ABC):
    @abstractmethod
    async def create(self, c: ConflictLog) -> ConflictLog: ...
    @abstractmethod
    async def update(self, c: ConflictLog) -> ConflictLog: ...
    @abstractmethod
    async def list(self, org_id: UUID, unresolved_only: bool = False, page: int = 1, per_page: int = 20) -> Tuple[List[ConflictLog], int]: ...
    @abstractmethod
    async def count_unresolved(self, org_id: UUID) -> int: ...


class SyncLogRepository(ABC):
    @abstractmethod
    async def create(self, l: SyncLog) -> SyncLog: ...
    @abstractmethod
    async def list(self, org_id: UUID, page: int = 1, per_page: int = 50) -> Tuple[List[SyncLog], int]: ...
