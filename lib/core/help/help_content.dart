  /// Static route catalog for assistant navigation: exact routes only
  /// (patterns containing `:id` are skipped), deduplicated, bilingual.
  static List<Map<String, String>> catalog({required bool arabic}) {
    final map = arabic ? _routesAr : _routesEn;
    final out = <Map<String, String>>[];
    final seen = <String>{};
    for (final e in map.entries) {
      final route = e.key;
      if (route.contains(':') || seen.contains(route)) continue;
      seen.add(route);
      out.add({
        'route': route,
        'title': e.value.$1,
        'summary': e.value.$2,
      });
    }
    return out;
  }
