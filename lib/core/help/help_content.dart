/// A short, user-facing explanation shown by the Information Clicker.
class HelpInfo {
  final String title;
  final String body;
  const HelpInfo(this.title, this.body);
}

/// Keyword rule: first matching stem wins; `{label}` is replaced by the
/// pressed label. Rules are spelling-robust (substring match) so compound
/// labels ("حفظ الفاتورة") are covered without a per-label entry.
class _Rule {
  final List<String> stems;
  final String body;
  const _Rule(this.stems, this.body);
}

/// Bilingual help-content registry for the Information Clicker.
///
/// Resolution order:
///   1. exact label (curated, most precise),
///   2. keyword rules (covers compound/dynamic labels),
///   3. current route/screen explanation (covers icon-only buttons),
///   4. a safe generic sentence (never empty).
class HelpContent {
  HelpContent._();

  static String _normalize(String raw) {
    var s = raw.trim();
    s = s.replaceAll(RegExp('[\u0617-\u061A\u064B-\u0652\u0670\u0640]'), '');
    // Strip emoji / pictographs (option labels like '🏦 حساب ثابت' carry
    // them): matching must work on the words, with or without icons.
    s = s.replaceAll(
        RegExp(
            '[\u2600-\u27BF\u2190-\u21FF\u2B00-\u2BFF\uFE00-\uFE0F\u200D\u{1F300}-\u{1FAFF}]',
            unicode: true),
        '');
    s = s.replaceAll(RegExp(r'\s+'), ' ');
    while (s.endsWith('*') || s.endsWith(':')) {
      s = s.substring(0, s.length - 1).trim();
    }
    return s;
  }

  static bool hasExactLabel(String label, {required bool arabic}) {
    final clean = _normalize(label);
    if (clean.isEmpty) return false;
    final labels = arabic ? _labelsAr : _labelsEn;
    final key = arabic ? clean : clean.toLowerCase();
    return labels.containsKey(key);
  }

  /// Whether any keyword rule (resolution level 2) covers [label].
  static bool hasRuleMatch(String label, {required bool arabic}) {
    final clean = _normalize(label);
    if (clean.isEmpty) return false;
    final hay = arabic ? clean : clean.toLowerCase();
    return (arabic ? _rulesAr : _rulesEn).any((r) => r.stems.any(hay.contains));
  }

  /// Whether [label] reads as UI copy rather than as user text: every one of
  /// its words must be covered by an exact entry or by a keyword rule.
  ///
  /// This is what separates "حفظ الفاتورة" (both words known) from an account
  /// or customer name such as "بنك التضامن" (the second word is free-form),
  /// which must never be turned into a help card.
  static bool isCoveredPhrase(String label, {required bool arabic}) {
    final clean = _normalize(label);
    if (clean.isEmpty) return false;
    final words = clean.split(' ');
    if (words.length > 4) return false;
    final labels = arabic ? _labelsAr : _labelsEn;
    final rules = arabic ? _rulesAr : _rulesEn;
    for (final raw in words) {
      final word = arabic ? raw : raw.toLowerCase();
      if (word.isEmpty) continue;
      if (labels.containsKey(word)) continue;
      if (rules.any((r) => r.stems.any(word.contains))) continue;
      return false;
    }
    return true;
  }

  /// Whether the current route has its own curated explanation (level 3).
  static bool hasRouteInfo(String route) {
    final path = route.split('?').first;
    if (path.isEmpty) return false;
    final keys = _routesAr.keys;
    if (keys.contains(path)) return true;
    return keys.any(path.startsWith);
  }

  static HelpInfo resolve({
    required String route,
    required String label,
    required bool arabic,
  }) {
    final clean = _normalize(label);
    final labels = arabic ? _labelsAr : _labelsEn;
    if (clean.isNotEmpty) {
      final key = arabic ? clean : clean.toLowerCase();
      final exact = labels[key];
      if (exact != null) return HelpInfo(clean, exact);
      for (final rule in (arabic ? _rulesAr : _rulesEn)) {
        final hay = arabic ? clean : clean.toLowerCase();
        if (rule.stems.any(hay.contains)) {
          return HelpInfo(clean, rule.body.replaceAll('{label}', clean));
        }
      }
    }
    final routeInfo = _routeInfo(route, arabic);
    if (routeInfo != null) return routeInfo;
    if (clean.isNotEmpty) {
      return HelpInfo(
        clean,
        arabic
            ? 'ينفّذ هذا الزر الإجراء الخاص به في هذه الشاشة.'
            : 'This button performs its action on this screen.',
      );
    }
    return HelpInfo(
      arabic ? 'معلومات' : 'Information',
      arabic
          ? 'اضغط مطولاً على أي زر أو قسم ليظهر شرحه هنا.'
          : 'Long-press any button or section to see its explanation here.',
    );
  }

  static HelpInfo? _routeInfo(String route, bool arabic) {
    final path = route.split('?').first;
    final map = arabic ? _routesAr : _routesEn;
    final exact = map[path];
    if (exact != null) return HelpInfo(exact.$1, exact.$2);
    MapEntry<String, (String, String)>? best;
    for (final e in map.entries) {
      if (path.startsWith(e.key) && (best == null || e.key.length > best.key.length)) {
        best = e;
      }
    }
    if (best != null) return HelpInfo(best.value.$1, best.value.$2);
    return null;
  }

