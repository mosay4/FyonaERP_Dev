/// port of backend `sara_analytics.build_financial_analytics` (Stage 5 of
/// docs/PERSONAL_LOCAL_PLAN.md). The server never reads Personal tables in
/// device mode; it sends the period window ([bounds], resolved in the user's
/// timezone) and the phone answers with the same bounded snapshot.
