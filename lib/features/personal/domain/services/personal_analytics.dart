/// rule. Output strings match Python's `str(Decimal)` exactly; parity is
/// pinned by test/fixtures/personal_analytics_parity.json, generated by the
/// backend implementation itself.
///
/// The optional cross-currency conversion is NOT done here: it uses the
/// server's public rates and is added by the server (`conversion`).
