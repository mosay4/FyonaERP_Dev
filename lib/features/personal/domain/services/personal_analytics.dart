/// Python `decimal.Decimal` subset with the default context (28 digits,
/// ROUND_HALF_EVEN): add/sub/mul/div/quantize and `str()` formatting.
class PyDecimal implements Comparable<PyDecimal> {
  final bool negative;
  final BigInt coefficient; // >= 0
  final int exponent;

  const PyDecimal._(this.negative, this.coefficient, this.exponent);

  static final zero = PyDecimal._(false, BigInt.zero, 0);
  static const _precision = 28;
  static final _ten = BigInt.from(10);

  /// Plain decimal text ("-12.50", "3"); null/garbage → 0 (Python `_d`).
  factory PyDecimal.parse(Object? value) {
    final text = '${value ?? ''}'.trim();
    final m = RegExp(r'^([+-]?)(\d*)(?:\.(\d*))?(?:[eE]([+-]?\d+))?$').firstMatch(text);
    if (text.isEmpty || m == null || ((m.group(2) ?? '') + (m.group(3) ?? '')).isEmpty) return zero;
    final whole = m.group(2) ?? '';
    final frac = m.group(3) ?? '';
    final exp = -frac.length + int.parse(m.group(4) ?? '0');
    return PyDecimal._(m.group(1) == '-', BigInt.parse('$whole$frac'.isEmpty ? '0' : '$whole$frac'), exp);
  }

  /// A stored money amount: NUMERIC(12,2) semantics (two decimals, as the
  /// server column stores it), from a number or decimal text.
  factory PyDecimal.money(Object? value) {
    if (value == null) return zero;
    if (value is num) {
      if (!value.isFinite) return zero;
      return PyDecimal.parse(value.toStringAsFixed(2));
    }
    final parsed = PyDecimal.parse(value);
    return parsed._roundTo(-2, halfEven: false);
  }

  BigInt get _signed => negative ? -coefficient : coefficient;
  bool get isZero => coefficient == BigInt.zero;

  static PyDecimal _fromSigned(BigInt value, int exp, {bool zeroNegative = false}) =>
      PyDecimal._(value.isNegative || (value == BigInt.zero && zeroNegative), value.abs(), exp);

  PyDecimal operator +(PyDecimal other) {
    final exp = exponent < other.exponent ? exponent : other.exponent;
    final a = _signed * _ten.pow(exponent - exp);
    final b = other._signed * _ten.pow(other.exponent - exp);
    return _fromSigned(a + b, exp, zeroNegative: negative && other.negative);
  }

  PyDecimal operator -() => PyDecimal._(!negative, coefficient, exponent);
  PyDecimal operator -(PyDecimal other) => this + (-other);

  PyDecimal operator *(PyDecimal other) =>
      PyDecimal._(negative != other.negative, coefficient * other.coefficient, exponent + other.exponent)._fix();

  /// Python `Decimal.__truediv__` (exact results keep the ideal exponent).
  PyDecimal operator /(PyDecimal other) {
    if (other.isZero) throw ArgumentError('division by zero');
    final sign = negative != other.negative;
    if (isZero) return PyDecimal._(sign, BigInt.zero, exponent - other.exponent);
    final shift = other.coefficient.toString().length - coefficient.toString().length + _precision + 1;
    var exp = exponent - other.exponent - shift;
    BigInt coeff, remainder;
    if (shift >= 0) {
      final n = coefficient * _ten.pow(shift);
      coeff = n ~/ other.coefficient;
      remainder = n.remainder(other.coefficient);
    } else {
      final d = other.coefficient * _ten.pow(-shift);
      coeff = coefficient ~/ d;
      remainder = coefficient.remainder(d);
    }
    if (remainder != BigInt.zero) {
      if (coeff % BigInt.from(5) == BigInt.zero) coeff += BigInt.one;
    } else {
      final ideal = exponent - other.exponent;
      while (exp < ideal && coeff % _ten == BigInt.zero) {
        coeff ~/= _ten;
        exp += 1;
      }
    }
    return PyDecimal._(sign, coeff, exp)._fix();
  }

  /// Round to [_precision] significant digits (context `_fix`).
  PyDecimal _fix() {
    final digits = coefficient.toString().length;
    if (digits <= _precision) return this;
    return _roundTo(exponent + digits - _precision)._fix();
  }

  /// Value rounded to [exp] (half-even, or half-up = PostgreSQL numeric).
  PyDecimal _roundTo(int exp, {bool halfEven = true}) {
    if (exponent == exp) return this;
    if (exponent > exp) {
      return PyDecimal._(negative, coefficient * _ten.pow(exponent - exp), exp);
    }
    final div = _ten.pow(exp - exponent);
    var q = coefficient ~/ div;
    final r = coefficient.remainder(div);
    final twice = r * BigInt.two;
    if (twice > div || (twice == div && (!halfEven || q.isOdd))) q += BigInt.one;
    return PyDecimal._(negative, q, exp);
  }

  /// `Decimal.quantize(Decimal('0.1'))` and friends (ROUND_HALF_EVEN).
  PyDecimal quantize(int exp) => _roundTo(exp);

  PyDecimal abs() => PyDecimal._(false, coefficient, exponent);

  @override
  int compareTo(PyDecimal other) => (this - other)._sign;
  int get _sign => isZero ? 0 : (negative ? -1 : 1);
  bool operator >(PyDecimal o) => compareTo(o) > 0;
  bool operator >=(PyDecimal o) => compareTo(o) >= 0;
  bool operator <(PyDecimal o) => compareTo(o) < 0;

  @override
  bool operator ==(Object other) => other is PyDecimal && compareTo(other) == 0;
  @override
  int get hashCode => toString().hashCode;

  /// Python `Decimal.__str__` (scientific notation only where Python uses it).
  @override
  String toString() {
    final d = coefficient.toString();
    final left = exponent + d.length;
    final dot = exponent <= 0 && left > -6 ? left : 1;
    String intPart, fracPart;
    if (dot <= 0) {
      intPart = '0';
      fracPart = '.${'0' * -dot}$d';
    } else if (dot >= d.length) {
      intPart = d + '0' * (dot - d.length);
      fracPart = '';
    } else {
      intPart = d.substring(0, dot);
      fracPart = '.${d.substring(dot)}';
    }
    final e = left - dot;
    final expPart = e == 0 ? '' : 'E${e > 0 ? '+' : ''}$e';
    return '${negative ? '-' : ''}$intPart$fracPart$expPart';
  }
}

/// The period window the server resolved (UTC edges, user timezone).
class AnalyticsBounds {
  final String period;
  final String start, end, prevStart, prevEnd;
  final String timezone;

  const AnalyticsBounds({
    required this.period,
    required this.start,
    required this.end,
    required this.prevStart,
    required this.prevEnd,
    required this.timezone,
  });

  factory AnalyticsBounds.fromJson(Map<String, dynamic> json) => AnalyticsBounds(
    period: '${json['period'] ?? 'this_month'}',
    start: '${json['start']}',
    end: '${json['end']}',
    prevStart: '${json['prev_start']}',
    prevEnd: '${json['prev_end']}',
    timezone: '${json['timezone'] ?? 'UTC'}',
  );

  /// Fallback when no server window came (this calendar month, UTC).
  factory AnalyticsBounds.thisMonthUtc(DateTime now) {
    final u = now.toUtc();
    final s = DateTime.utc(u.year, u.month);
    final e = DateTime.utc(u.year, u.month + 1);
    final len = e.difference(s);
    return AnalyticsBounds(period: 'this_month', start: pyIso(s), end: pyIso(e),
        prevStart: pyIso(s.subtract(len)), prevEnd: pyIso(s), timezone: 'UTC');
  }

  DateTime get startAt => DateTime.parse(start).toUtc();
  DateTime get endAt => DateTime.parse(end).toUtc();
  DateTime get prevStartAt => DateTime.parse(prevStart).toUtc();
  DateTime get prevEndAt => DateTime.parse(prevEnd).toUtc();
}

String _two(int v) => v.toString().padLeft(2, '0');

/// Python `datetime.isoformat()` of a UTC-aware datetime.
String pyIso(DateTime t, {String sep = 'T'}) {
  final u = t.toUtc();
  final micro = u.millisecond * 1000 + u.microsecond;
  return '${u.year.toString().padLeft(4, '0')}-${_two(u.month)}-${_two(u.day)}$sep'
      '${_two(u.hour)}:${_two(u.minute)}:${_two(u.second)}'
      '${micro == 0 ? '' : '.${micro.toString().padLeft(6, '0')}'}+00:00';
}

DateTime? _time(Object? v) {
  if (v == null) return null;
  if (v is DateTime) return v.toUtc();
  final text = '$v'.trim();
  if (text.isEmpty) return null;
  final parsed = DateTime.tryParse(text);
  if (parsed == null) return null;
  if (parsed.isUtc || RegExp(r'([+-]\d{2}:?\d{2}|Z)$').hasMatch(text)) return parsed.toUtc();
  // Stored timestamps without an offset are UTC (server convention).
  return DateTime.utc(parsed.year, parsed.month, parsed.day, parsed.hour, parsed.minute,
      parsed.second, parsed.millisecond, parsed.microsecond);
}

/// Python `str(date)` of a stored calendar day, or ''.
String _dayText(Object? v) {
  if (v == null) return '';
  if (v is DateTime) return '${v.year.toString().padLeft(4, '0')}-${_two(v.month)}-${_two(v.day)}';
  final text = '$v'.trim();
  final m = RegExp(r'^(\d{4}-\d{2}-\d{2})').firstMatch(text);
  return m?.group(1) ?? text;
}

String _cur(Object? v) {
  final text = '${v ?? ''}';
  return (text.isEmpty ? 'SAR' : text).toUpperCase();
}

String _s(Object? v) => v == null ? '' : '$v';

(String?, String) _pct(PyDecimal num, PyDecimal den) {
  if (den.isZero) return (null, num.isZero ? 'flat' : 'new');
  final pct = (num / den * PyDecimal.parse('100')).quantize(-1);
  if (num.isZero) return ('0.0', 'flat');
  return (pct.toString(), num.negative ? 'down' : 'up');
}

/// Stable sort (Python `sorted`/`list.sort` are stable; Dart's is not).
List<T> _stable<T>(Iterable<T> items, int Function(T a, T b) compare) {
  final indexed = [for (final (i, e) in items.indexed) (i, e)];
  indexed.sort((a, b) {
    final c = compare(a.$2, b.$2);
    return c != 0 ? c : a.$1.compareTo(b.$1);
  });
  return [for (final e in indexed) e.$2];
}

class _Tx {
  final Map<String, dynamic> row;
  final DateTime? date;
  final PyDecimal amount;
  _Tx(this.row) : date = _time(row['date']), amount = PyDecimal.money(row['amount']);
  String get type => _s(row['tx_type']);
  String get currency => _cur(row['currency']);
  String get category => _s(row['category']);
  String? get account => _id(row['bank_account_id']);
  bool inWindow(DateTime s, DateTime e) => date != null && !date!.isBefore(s) && date!.isBefore(e);
}

String? _id(Object? v) {
  final text = v == null ? '' : '$v'.trim();
  return text.isEmpty ? null : text;
}

class _Group {
  PyDecimal total = PyDecimal.zero;
  int count = 0;
  void add(PyDecimal v) {
    total = total + v;
    count++;
  }
}

Map<K, _Group> _group<K>(Iterable<_Tx> rows, K Function(_Tx) key) {
  final out = <K, _Group>{};
  for (final t in rows) {
    out.putIfAbsent(key(t), _Group.new).add(t.amount);
  }
  return out;
}

/// The analytics snapshot from this device's rows. Row maps use the
/// server's field names (see the parity fixture and [PersonalAnalytics.rowsFrom]).
abstract final class PersonalAnalytics {
  static Map<String, dynamic> build({
    required List<Map<String, dynamic>> accounts,
    required List<Map<String, dynamic>> transactions,
    required List<Map<String, dynamic>> budgets,
    required List<Map<String, dynamic>> goals,
    required List<Map<String, dynamic>> debts,
    required List<Map<String, dynamic>> recurring,
    required AnalyticsBounds bounds,
    DateTime? generatedAt,
  }) {
    final start = bounds.startAt, end = bounds.endAt;
    final prevStart = bounds.prevStartAt, prevEnd = bounds.prevEndAt;
    final txs = [for (final t in transactions) _Tx(t)];
    final missing = <Map<String, String>>[];
    Iterable<_Tx> window(DateTime s, DateTime e) => txs.where((t) => t.inWindow(s, e));
    final period = window(start, end).toList();

    // ── facts: income/expense/net per currency ────────────────────────────
    Map<String, Map<String, Object>> sums(DateTime s, DateTime e) {
      final out = <String, Map<String, Object>>{};
      for (final type in const ['income', 'expense']) {
        final groups = _group(window(s, e).where((t) => t.type == type), (t) => t.currency);
        for (final MapEntry(key: code, value: g) in groups.entries) {
          final slot = out.putIfAbsent(code, () => {
            'income': PyDecimal.zero, 'expense': PyDecimal.zero,
            'income_count': 0, 'expense_count': 0});
          slot[type] = (slot[type] as PyDecimal) + g.total;
          slot['${type}_count'] = g.count;
        }
      }
      return out;
    }

    final curSums = sums(start, end), prevSums = sums(prevStart, prevEnd);
    final codes = ({...curSums.keys, ...prevSums.keys}.toList()..sort());
    PyDecimal val(Map<String, Object>? m, String k) => (m?[k] as PyDecimal?) ?? PyDecimal.zero;
    final factsMoney = [
      for (final code in codes)
        {
          'currency_id': code, 'currency': code,
          'income': '${val(curSums[code], 'income')}',
          'expense': '${val(curSums[code], 'expense')}',
          'net': '${val(curSums[code], 'income') - val(curSums[code], 'expense')}',
          'income_count': curSums[code]?['income_count'] ?? 0,
          'expense_count': curSums[code]?['expense_count'] ?? 0,
        },
    ];

    // ── facts: transfers (category-labelled legs) ─────────────────────────
    final transferGroups = _group(period.where((t) => _transferCategories.contains(t.category)),
        (t) => (t.type, t.currency));
    final transferKeys = _stable(transferGroups.keys, (a, b) {
      final c = a.$1.compareTo(b.$1);
      return c != 0 ? c : a.$2.compareTo(b.$2);
    });
    final transfers = [
      for (final k in transferKeys)
        {'direction': k.$1, 'currency_id': k.$2, 'currency': k.$2,
         'total': '${transferGroups[k]!.total}', 'count': transferGroups[k]!.count},
    ];

    List<Map<String, dynamic>> topBy(String type, int limit) {
      final groups = _group(period.where((t) => t.type == type), (t) => (t.category, t.currency));
      final keys = _stable(groups.keys, (a, b) => groups[b]!.total.compareTo(groups[a]!.total)).take(limit);
      return [
        for (final k in keys)
          {'category': k.$1, 'currency_id': k.$2, 'currency': k.$2,
           'total': '${groups[k]!.total}', 'tx_count': groups[k]!.count},
      ];
    }

    final topCategories = topBy('expense', _topCategories);
    if (topCategories.isEmpty) missing.add({'block': 'top_categories', 'reason': 'no_expenses_in_period'});
    final incomeSources = topBy('income', _incomeSources);
    if (incomeSources.isEmpty) missing.add({'block': 'income_sources', 'reason': 'no_income_in_period'});

    // ── facts: banks (balance + period flows per account per currency) ────
    final flows = <String, Map<String, Map<String, Map<String, Object>>>>{};
    final flowGroups = _group(period, (t) => (t.account ?? 'unassigned', t.type, t.currency));
    for (final MapEntry(key: k, value: g) in flowGroups.entries) {
      final slot = flows.putIfAbsent(k.$1, () => {'in': {}, 'out': {}});
      final bucket = slot[k.$2 == 'income' ? 'in' : 'out']!;
      final prev = bucket[k.$3];
      bucket[k.$3] = {
        'total': '${PyDecimal.parse(prev?['total'] ?? '0') + g.total}',
        'count': ((prev?['count'] as int?) ?? 0) + g.count,
      };
    }
    final banks = <Map<String, dynamic>>[
      for (final a in accounts.take(_maxAccounts))
        {
          'account_id': _s(a['id']),
          'account_name': a['bank_name'],
          'currency_id': _cur(a['currency']), 'currency': _cur(a['currency']),
          'balance': '${PyDecimal.money(a['balance'])}',
          'period_in': flows[_s(a['id'])]?['in'] ?? {},
          'period_out': flows[_s(a['id'])]?['out'] ?? {},
        },
    ];
    if (banks.isEmpty) missing.add({'block': 'banks', 'reason': 'no_accounts'});
    if (flows.containsKey('unassigned')) {
      banks.add({'account_id': null, 'account_name': null, 'unassigned': true,
        'period_in': flows['unassigned']!['in'], 'period_out': flows['unassigned']!['out']});
    }

    // ── facts: budgets ─────────────────────────────────────────────────────
    final budgetRows = [
      for (final b in budgets.take(_maxBudgets))
        () {
          final total = PyDecimal.money(b['total_amount']);
          // Python: `getattr(b, "spent", 0) or 0` — a zero amount is falsy,
          // so a zero spend prints as "0", never "0.00".
          final stored = PyDecimal.money(b['spent'] ?? 0);
          final spent = stored.isZero ? PyDecimal.zero : stored;
          final (pct, _) = _pct(spent, total);
          return <String, dynamic>{
            'budget_id': _s(b['id']), 'name': b['name'],
            'currency_id': _cur(b['currency']), 'currency': _cur(b['currency']),
            'total': '$total', 'spent': '$spent', 'remaining': '${total - spent}',
            'used_pct': pct, 'used_num': '$spent', 'used_den': '$total',
            'period': b['period_type'],
            'categories': [
              for (final c in ((b['categories'] as List?) ?? const []).whereType<Map>().take(_maxBudgetCategories))
                () {
                  final alloc = PyDecimal.money(c['allocated_amount'] ?? 0);
                  final used = PyDecimal.money(c['spent_amount'] ?? 0);
                  return {
                    'category_id': _s(c['id']), 'name': c['name'], 'type': c['type'],
                    'currency_id': _cur(c['currency']), 'currency': _cur(c['currency']),
                    'allocated': '$alloc', 'spent': '$used', 'remaining': '${alloc - used}',
                  };
                }(),
            ],
            'linked_expense_count': period.where((t) => _id(t.row['budget_id']) == _s(b['id'])).length,
          };
        }(),
    ];
    if (budgetRows.isEmpty) missing.add({'block': 'budgets', 'reason': 'no_budgets'});

    int newestFirst(DateTime? a, DateTime? b) =>
        (b ?? DateTime.utc(0)).compareTo(a ?? DateTime.utc(0));

    // ── facts: goals (+ recent contributions via goal_id) ─────────────────
    final goalRows = [
      for (final g in goals.take(_maxBudgets))
        () {
          final target = PyDecimal.money(g['target_amount']);
          final current = PyDecimal.money(g['current_amount'] ?? 0);
          final (pct, _) = _pct(current, target);
          final linked = _stable(txs.where((t) => _id(t.row['goal_id']) == _s(g['id'])),
              (a, b) => newestFirst(a.date, b.date)).take(_linkedRows);
          return <String, dynamic>{
            'goal_id': _s(g['id']), 'name': g['name'],
            'currency_id': _cur(g['currency']), 'currency': _cur(g['currency']),
            'target': '$target', 'current': '$current', 'remaining': '${target - current}',
            'progress_pct': pct, 'progress_num': '$current', 'progress_den': '$target',
            'deadline': _dayText(g['deadline']),
            'is_completed': g['is_completed'] == true,
            'recent_contributions': [
              for (final t in linked)
                {
                  'tx_id': _s(t.row['id']),
                  'amount': '${t.row['goal_amount'] != null ? PyDecimal.money(t.row['goal_amount']) : t.amount}',
                  'tx_currency_id': t.currency,
                  'date': t.date == null ? '' : pyIso(t.date!),
                },
            ],
          };
        }(),
    ];
    if (goalRows.isEmpty) missing.add({'block': 'goals', 'reason': 'no_goals'});

    // ── facts: debts (paid = exact sum of payment rows) ───────────────────
    final debtRows = [
      for (final d in debts.take(_maxBudgets))
        () {
          final payments = ((d['payments'] as List?) ?? const []).whereType<Map>().toList();
          // COALESCE(SUM(no rows), 0) is the integer 0 on PostgreSQL.
          var paid = PyDecimal.zero;
          for (final p in payments) {
            paid = paid + PyDecimal.money(p['amount']);
          }
          final original = PyDecimal.money(d['amount']);
          final recent = _stable(payments, (a, b) => newestFirst(_time(a['payment_date']), _time(b['payment_date'])))
              .take(_linkedRows);
          return <String, dynamic>{
            'debt_id': _s(d['id']), 'name': d['person_name'],
            'debt_type': d['debt_type'] ?? '',
            'currency_id': _cur(d['currency']), 'currency': _cur(d['currency']),
            'original': '$original', 'paid': '$paid', 'remaining': '${original - paid}',
            'payment_count': payments.length,
            'due_date': _dayText(d['due_date']),
            'is_paid': d['is_paid'] == true,
            'recent_payments': [
              for (final p in recent)
                {
                  'payment_id': _s(p['id']), 'amount': '${PyDecimal.money(p['amount'])}',
                  'currency_id': _cur(p['currency']),
                  'date': _time(p['payment_date']) == null ? '' : pyIso(_time(p['payment_date'])!),
                },
            ],
          };
        }(),
    ];
    if (debtRows.isEmpty) missing.add({'block': 'debts', 'reason': 'no_debts'});

    // ── facts: recurring (active first, bounded) ──────────────────────────
    final names = {for (final a in accounts) _s(a['id']): a['bank_name']};
    final recurringRows = [
      for (final r in _stable(recurring, (a, b) => (b['is_active'] != false ? 1 : 0) - (a['is_active'] != false ? 1 : 0))
          .take(_maxRecurring))
        {
          'recurring_id': _s(r['id']), 'name': _s(r['name']),
          'currency_id': _cur(r['currency']), 'currency': _cur(r['currency']),
          'amount': '${PyDecimal.money(r['amount'])}', 'tx_type': r['tx_type'],
          'frequency': r['frequency'], 'interval': r['interval_value'],
          'category': _s(r['category']),
          'account_id': _id(r['bank_account_id']),
          'account_name': _id(r['bank_account_id']) == null ? null : names[_id(r['bank_account_id'])],
          'last_run': _time(r['last_executed_at']) == null ? '' : pyIso(_time(r['last_executed_at'])!, sep: ' '),
          'next_run': _dayText(r['next_run_date']),
          'is_active': r['is_active'] != false,
        },
    ];
    if (recurringRows.isEmpty) missing.add({'block': 'recurring', 'reason': 'no_recurring'});

    // ── comparisons: current vs previous EQUAL window, per currency ───────
    final comparisons = <Map<String, dynamic>>[];
    for (final code in codes) {
      final c = curSums[code], p = prevSums[code];
      for (final kind in const ['income', 'expense', 'net']) {
        final cv = kind == 'net' ? val(c, 'income') - val(c, 'expense') : val(c, kind);
        final pv = kind == 'net' ? val(p, 'income') - val(p, 'expense') : val(p, kind);
        final delta = cv - pv;
        final (disp, status) = _pct(delta, pv);
        comparisons.add({
          'currency_id': code, 'currency': code, 'metric': kind,
          'current': '$cv', 'previous': '$pv', 'delta': '$delta',
          'delta_pct': disp, 'delta_num': '$delta', 'delta_den': '$pv', 'trend': status,
        });
      }
    }
    Map<(String, String), PyDecimal> catSums(DateTime s, DateTime e) => {
      for (final MapEntry(key: k, value: g)
          in _group(window(s, e).where((t) => t.type == 'expense'), (t) => (t.category, t.currency)).entries)
        k: g.total,
    };
    final curCats = catSums(start, end), prevCats = catSums(prevStart, prevEnd);
    final movers = <Map<String, dynamic>>[];
    for (final k in {...curCats.keys, ...prevCats.keys}) {
      final cv = curCats[k] ?? PyDecimal.zero, pv = prevCats[k] ?? PyDecimal.zero;
      if (cv == pv) continue;
      final (disp, status) = _pct(cv - pv, pv);
      movers.add({'category': k.$1, 'currency_id': k.$2, 'currency': k.$2,
        'current': '$cv', 'previous': '$pv', 'delta': '${cv - pv}',
        'delta_pct': disp, 'trend': status});
    }
    final topMovers = _stable(movers, (a, b) =>
        PyDecimal.parse(b['delta']).abs().compareTo(PyDecimal.parse(a['delta']).abs())).take(_topCategories).toList();

    // ── detections: the ONE anomaly rule + insufficient-history ledger ────
    final baseStart = start.subtract(const Duration(days: _anomalyLookbackDays));
    final base = _group(window(baseStart, start).where((t) => t.type == 'expense'), (t) => (t.category, t.currency));
    final ratio3 = PyDecimal.parse('3');
    final anomalies = <(PyDecimal, Map<String, dynamic>)>[];
    final thin = <(String, String), int>{};
    final byAmount = _stable(period.where((t) => t.type == 'expense'), (a, b) => b.amount.compareTo(a.amount));
    for (final t in byAmount.take(50)) {
      final key = (t.category, t.currency);
      final g = base[key];
      final n = g?.count ?? 0;
      if (n < _anomalyMinBaseTx) {
        thin[key] = n;
        continue;
      }
      final mean = g!.total / PyDecimal.parse('$n');
      if (mean > PyDecimal.zero && t.amount >= ratio3 * mean) {
        final ratio = (t.amount / mean).quantize(-1);
        anomalies.add((ratio, {
          'tx_id': _s(t.row['id']), 'name': _s(t.row['description']),
          'amount': '${t.amount}', 'currency_id': key.$2, 'currency': key.$2,
          'category': key.$1, 'category_mean_90d': '$mean', 'base_tx_count': n,
          'ratio': '$ratio', 'rule': 'amount >= 3x category mean (90d, n=$n)',
          'date': t.date == null ? '' : pyIso(t.date!),
        }));
      }
    }
    final sortedAnomalies = _stable(anomalies, (a, b) => b.$1.compareTo(a.$1)).map((e) => e.$2).take(_topExpenses).toList();
    final thinKeys = thin.keys.toList()
      ..sort((a, b) {
        final c = a.$1.compareTo(b.$1);
        return c != 0 ? c : a.$2.compareTo(b.$2);
      });
    final detections = {
      'rule': 'expense >= 3x its (category, currency) 90-day mean with >= $_anomalyMinBaseTx base transactions',
      'anomalies': sortedAnomalies,
      'insufficient_history': [
        for (final k in thinKeys) {'category': k.$1, 'currency_id': k.$2, 'base_tx_count': thin[k]},
      ],
    };
    if (sortedAnomalies.isEmpty) {
      missing.add({'block': 'anomalies', 'reason': 'no_anomaly_by_rule_or_thin_history'});
    }

    // ── details: top expenses + recent, frequent descriptions ─────────────
    final accNames = {
      for (final b in banks)
        if (b['account_id'] != null) b['account_id']: b['account_name'],
    };
    Map<String, dynamic> txRow(_Tx t) => {
      'tx_id': _s(t.row['id']), 'name': _s(t.row['description']),
      'amount': '${t.amount}', 'currency_id': t.currency, 'currency': t.currency,
      'tx_type': t.type, 'date': t.date == null ? '' : pyIso(t.date!),
      'account_id': t.account, 'account_name': t.account == null ? null : accNames[t.account],
      'category': t.category, 'notes': _s(t.row['description']),
    };
    final topExpenseRows = [for (final t in byAmount.take(_topExpenses)) txRow(t)];
    final recentRows = [
      for (final t in _stable(period, (a, b) => newestFirst(a.date, b.date)).take(_recentTx)) txRow(t),
    ];
    if (recentRows.isEmpty) missing.add({'block': 'transactions', 'reason': 'no_transactions_in_period'});
    final freqByCur = <(String, String), _Group>{};
    for (final t in window(baseStart, end)) {
      final desc = (t.row['description'] as Object?)?.toString();
      freqByCur.putIfAbsent((desc ?? '\u0000', t.currency), _Group.new).add(t.amount);
    }
    final frequent = [
      for (final k in _stable(freqByCur.keys.where((k) => freqByCur[k]!.count >= 3),
          (a, b) => freqByCur[b]!.count - freqByCur[a]!.count).take(5))
        {'name': k.$1 == '\u0000' ? '' : k.$1, 'currency_id': k.$2, 'currency': k.$2,
         'occurrences_90d': freqByCur[k]!.count, 'total_90d': '${freqByCur[k]!.total}'},
    ];

    return {
      'meta': {
        'period': bounds.period,
        'period_start': bounds.start, 'period_end': bounds.end,
        'prev_start': bounds.prevStart, 'prev_end': bounds.prevEnd,
        'timezone': bounds.timezone,
        'source': 'device',
        'generated_at': pyIso(generatedAt ?? DateTime.now()),
      },
      'facts': {
        'money_by_currency': factsMoney,
        'transfers': transfers,
        'top_expense_categories': topCategories,
        'income_sources': incomeSources,
        'banks': banks,
        'budgets': budgetRows,
        'goals': goalRows,
        'debts': debtRows,
        'recurring': recurringRows,
      },
      'comparisons': {'per_currency': comparisons, 'category_movers': topMovers},
      'detections': detections,
      'details': {
        'top_expenses': topExpenseRows,
        'recent_transactions': recentRows,
        'frequent_descriptions_90d': frequent,
      },
      'missing': missing,
      'conversion': {'status': 'not_requested'},
    };
  }

  /// Ledger models → the row maps [build] reads (server field names).
  static Map<String, List<Map<String, dynamic>>> rowsFrom({
    required List<PersonalBankAccount> accounts,
    required List<PersonalTransaction> transactions,
    required List<PersonalBudget> budgets,
    required List<SavingsGoal> goals,
    required List<PersonalDebt> debts,
    required Map<String, List<PersonalDebtPayment>> payments,
    required List<RecurringTransaction> recurring,
  }) => {
    'accounts': [
      for (final a in accounts)
        {'id': a.id, 'bank_name': a.bankName, 'currency': a.currency, 'balance': a.balance},
    ],
    'transactions': [
      for (final t in transactions)
        {
          'id': t.id, 'tx_type': t.type, 'amount': t.amount, 'currency': t.currency,
          'category': t.category, 'description': t.description, 'bank_account_id': t.accountId,
          'budget_id': t.budgetId, 'goal_id': t.goalId, 'goal_amount': t.goalAmount,
          'date': t.date?.toUtc(),
        },
    ],
    'budgets': [
      for (final b in budgets)
        {
          'id': b.id, 'name': b.name, 'currency': b.currency, 'total_amount': b.totalAmount,
          'spent': b.totalSpent, 'period_type': b.periodType,
          'categories': [
            for (final c in b.categories)
              {'id': c.id, 'name': c.name, 'type': c.type, 'allocated_amount': c.allocatedAmount,
               'spent_amount': c.spentAmount, 'currency': c.currency},
          ],
        },
    ],
    'goals': [
      for (final g in goals)
        {'id': g.id, 'name': g.name, 'currency': g.currency, 'target_amount': g.targetAmount,
         'current_amount': g.currentAmount, 'deadline': g.deadline, 'is_completed': g.isCompleted},
    ],
    'debts': [
      for (final d in debts)
        {
          'id': d.id, 'person_name': d.personName, 'debt_type': d.type, 'currency': d.currency,
          'amount': d.amount, 'due_date': d.dueDate, 'is_paid': d.isPaid,
          'payments': [
            for (final p in payments[d.id] ?? const <PersonalDebtPayment>[])
              {'id': p.id, 'amount': p.amount, 'currency': p.currency, 'payment_date': p.paymentDate.toUtc()},
          ],
        },
    ],
    'recurring': [
      for (final r in recurring)
        {
          'id': r.id, 'name': r.name, 'currency': r.currency, 'amount': r.amount, 'tx_type': r.type,
          'frequency': r.frequency, 'interval_value': r.intervalValue, 'category': r.category,
          'bank_account_id': r.bankAccountId, 'last_executed_at': r.lastExecutedAt?.toUtc(),
          'next_run_date': r.nextDate, 'is_active': r.isActive,
        },
    ],
  };
