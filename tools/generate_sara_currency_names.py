"""Generate Sara-only display names from the backend's same CLDR catalog."""
import json
import sys
from pathlib import Path

root = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(root / 'backend'))
from app.domain.services.sara_presentation import currency_catalog, currency_name

lines = ['// Generated by tools/generate_sara_currency_names.py. Display only.']
for language, suffix in [('ar', 'Ar'), ('en', 'En')]:
    lines.append(f'const saraCurrencyNames{suffix} = <String, String>{{')
    for code in currency_catalog():
        lines.append(f'  {json.dumps(code)}: {json.dumps(currency_name(code, language), ensure_ascii=False)},')
    lines.append('};')
target = root / 'lib/features/ai/domain/agent/sara_currency_names.dart'
target.write_text('\n'.join(lines) + '\n')
print('Generated Sara currency names:', len(currency_catalog()))
